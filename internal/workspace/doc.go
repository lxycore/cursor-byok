// Package workspace 提供基于"编辑事件 + 内容寻址存储 + 工作区索引"的
// 文件版本管理与多对话并发协调能力。
//
// 设计原则：
//   - 磁盘是唯一真相：任何展示、跳转、冲突检测都以磁盘现状为准。
//   - 编辑在源头捕获：不在事后从对话 history 反推，而是在
//     PatchEdit/Write 完成回调里直接记录完整编辑事件。
//   - 存储与展示分离：内容存内容寻址 blob（去重），元数据存编辑日志。
//   - 绝不静默失败：所有写盘返回 error；覆盖用户手改必须有快照 + 事件。
//   - 并发不阻塞、冲突不丢：多对话并行写文件时行级不重叠自动合并，
//     重叠则快照 + 协调事件 + 可配置策略。
//   - 不依赖 git：有 git / 无 git 两种项目场景同一套机制。
